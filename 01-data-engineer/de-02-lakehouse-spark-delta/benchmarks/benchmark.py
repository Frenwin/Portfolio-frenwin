"""Measure what the lakehouse design buys, after `python -m lakehouse.pipeline` has run.

Writes docs/benchmark.json and docs/benchmark.md:
  * rows per table and why rows were rejected
  * one-day query time on bronze (no date partition) vs silver (partitioned by pickup_date)
  * file count before/after OPTIMIZE
  * time travel: silver at version 0 vs now
  * idempotency: re-running a month through silver
"""

from __future__ import annotations

import json
import statistics
import time
from pathlib import Path

from delta.tables import DeltaTable
from pyspark.sql import functions as F

from lakehouse import silver
from lakehouse.config import build_spark, tables_from_env

DAY = "2024-02-14"
OUT = Path("docs")


def median_seconds(fn, runs: int = 5) -> float:
    fn()  # warm-up: JVM, Delta log cache
    samples = []
    for _ in range(runs):
        t = time.perf_counter()
        fn()
        samples.append(time.perf_counter() - t)
    return round(statistics.median(samples), 2)


def main() -> None:
    tables = tables_from_env()
    spark = build_spark("lakehouse-benchmark", tables.root)
    load = lambda path: spark.read.format("delta").load(path)  # noqa: E731
    result: dict = {}

    result["rows"] = {
        "bronze.yellow_trips": load(tables.bronze_trips).count(),
        "silver.trips": load(tables.silver_trips).count(),
        "silver.trips_rejected": load(tables.silver_rejected).count(),
        "gold.daily_zone_demand": load(tables.gold_daily_zone_demand).count(),
        "gold.hourly_demand": load(tables.gold_hourly_demand).count(),
        "gold.daily_kpis": load(tables.gold_daily_kpis).count(),
    }
    result["reject_reasons"] = {
        r["reject_reason"]: r["count"]
        for r in load(tables.silver_rejected).groupBy("reject_reason").count().orderBy(F.desc("count")).collect()
    }

    def bronze_query():
        return (
            load(tables.bronze_trips).where(F.to_date("pickup_ts") == DAY)
            .groupBy("pu_location_id").count().collect()
        )

    def silver_query():
        return (
            load(tables.silver_trips).where(F.col("pickup_date") == DAY)
            .groupBy("pu_location_id").count().collect()
        )

    result["one_day_query"] = {
        "day": DAY,
        "bronze_seconds": median_seconds(bronze_query),
        "silver_seconds": median_seconds(silver_query),
        "bronze_trips": sum(r["count"] for r in bronze_query()),
        "silver_trips": sum(r["count"] for r in silver_query()),
    }

    history = DeltaTable.forPath(spark, tables.silver_trips).history()
    optimize = history.where(F.col("operation") == "OPTIMIZE").orderBy(F.desc("version")).first()
    if optimize:
        m = optimize["operationMetrics"]
        result["optimize"] = {
            "files_removed": int(m["numRemovedFiles"]),
            "files_added": int(m["numAddedFiles"]),
        }
    detail = DeltaTable.forPath(spark, tables.silver_trips).detail().first()
    result["silver_layout"] = {
        "files": detail["numFiles"],
        "size_mb": round(detail["sizeInBytes"] / 1e6, 1),
        "partition_columns": list(detail["partitionColumns"]),
    }

    result["time_travel"] = {
        "versions": history.count(),
        "rows_at_version_0": spark.read.format("delta").option("versionAsOf", 0).load(tables.silver_trips).count(),
        "rows_now": result["rows"]["silver.trips"],
    }

    t = time.perf_counter()
    rerun = silver.process_month(spark, tables, "2024-01")
    result["idempotent_rerun"] = {
        "month": "2024-01",
        "rows_inserted": rerun.inserted,
        "rows_deleted": rerun.deleted,
        "seconds": round(time.perf_counter() - t, 1),
    }

    OUT.mkdir(exist_ok=True)
    (OUT / "benchmark.json").write_text(json.dumps(result, indent=2), encoding="utf-8")
    (OUT / "benchmark.md").write_text(render(result), encoding="utf-8")
    print(json.dumps(result, indent=2))
    spark.stop()


def render(r: dict) -> str:
    q = r["one_day_query"]
    lines = [
        "# Benchmark results",
        "",
        "Generated by `python -m benchmarks.benchmark` on a laptop (Spark local mode in Docker).",
        "",
        "## Rows per table",
        "",
        "| Table | Rows |",
        "| --- | ---: |",
        *[f"| `{k}` | {v:,} |" for k, v in r["rows"].items()],
        "",
        "## Why rows were rejected",
        "",
        "| Reason | Rows |",
        "| --- | ---: |",
        *[f"| `{k}` | {v:,} |" for k, v in r["reject_reasons"].items()],
        "",
        f"## One-day query ({q['day']}, trips per pickup zone)",
        "",
        "| Table | Layout | Median time (s) | Trips found |",
        "| --- | --- | ---: | ---: |",
        f"| bronze | partitioned by source month only | {q['bronze_seconds']} | {q['bronze_trips']:,} |",
        f"| silver | partitioned by `pickup_date` | {q['silver_seconds']} | {q['silver_trips']:,} |",
        "",
        "Silver finds fewer trips because invalid and duplicate rows were removed.",
        "",
        "## Layout and maintenance",
        "",
        f"- Silver: {r['silver_layout']['files']} files, {r['silver_layout']['size_mb']} MB, partitioned by {', '.join(r['silver_layout']['partition_columns'])}",
    ]
    if "optimize" in r:
        lines.append(f"- OPTIMIZE + Z-ORDER: {r['optimize']['files_removed']} files compacted into {r['optimize']['files_added']}")
    tt, rr = r["time_travel"], r["idempotent_rerun"]
    lines += [
        f"- Time travel: {tt['versions']} versions; version 0 holds {tt['rows_at_version_0']:,} rows, the latest {tt['rows_now']:,}",
        f"- Re-running {rr['month']} through silver: {rr['rows_inserted']} inserted, {rr['rows_deleted']} deleted ({rr['seconds']} s)",
        "",
    ]
    return "\n".join(lines)


if __name__ == "__main__":
    main()
