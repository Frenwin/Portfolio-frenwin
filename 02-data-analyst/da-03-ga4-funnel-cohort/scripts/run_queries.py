"""Run every query in queries/ on BigQuery and write docs/answers.md + docs/answers.json.

Each query is dry-run first to report how many bytes it will scan (the BigQuery sandbox
gives 1 TB of free queries per month; this whole project scans a few GB).

Usage:
    set GCP_PROJECT=<your project id>     (PowerShell: $env:GCP_PROJECT = "...")
    python scripts/run_queries.py
"""

from __future__ import annotations

import datetime as dt
import decimal
import json
import os
import time
from pathlib import Path

from google.cloud import bigquery

ROOT = Path(__file__).resolve().parents[1]


def fmt(v) -> str:
    if v is None:
        return ""
    if isinstance(v, bool):
        return str(v)
    if isinstance(v, int):
        return f"{v:,}"
    if isinstance(v, float):
        return f"{v:,.0f}" if abs(v) >= 1000 else f"{v:g}"
    return str(v)


def header(sql: str) -> tuple[str, str]:
    comments = []
    for line in sql.splitlines():
        if not line.startswith("--"):
            break
        comments.append(line[2:].strip())
    question = comments[0] if comments else ""
    technique = " ".join(comments[1:]).removeprefix("Techniques:").strip()
    return question, technique


def jsonable(v):
    if isinstance(v, (dt.date, dt.datetime)):
        return v.isoformat()
    if isinstance(v, decimal.Decimal):
        return float(v)
    return v


def main() -> None:
    project = os.environ.get("GCP_PROJECT")
    client = bigquery.Client(project=project)
    out = [
        "# Answers",
        "",
        "Generated by `python scripts/run_queries.py` on BigQuery against "
        "`bigquery-public-data.ga4_obfuscated_sample_ecommerce` (1 Nov 2020 - 31 Jan 2021).",
        "",
    ]
    results, total_bytes = {}, 0
    for path in sorted((ROOT / "queries").glob("q*.sql")):
        sql = path.read_text(encoding="utf-8")
        question, technique = header(sql)
        dry = client.query(sql, job_config=bigquery.QueryJobConfig(dry_run=True, use_query_cache=False))
        scanned = dry.total_bytes_processed or 0
        total_bytes += scanned
        t = time.perf_counter()
        rows = list(client.query(sql).result())
        secs = time.perf_counter() - t
        columns = list(rows[0].keys()) if rows else []
        results[path.stem] = {"columns": columns, "rows": [[jsonable(r[c]) for c in columns] for r in rows],
                              "bytes_scanned": scanned}
        out += [
            f"## {question}",
            "",
            f"**SQL techniques:** {technique} · [`{path.name}`](../queries/{path.name}) · "
            f"{scanned / 1e9:.2f} GB scanned · {secs:.1f} s",
            "",
            "| " + " | ".join(columns) + " |",
            "| " + " | ".join("---" for _ in columns) + " |",
            *["| " + " | ".join(fmt(r[c]) for c in columns) + " |" for r in rows[:60]],
            "",
        ]
        if len(rows) > 60:
            out += [f"_{len(rows)} rows; first 60 shown. Full result in answers.json._", ""]
        print(f"{path.name}: {len(rows)} rows, {scanned / 1e9:.2f} GB, {secs:.1f} s")
    out.insert(4, f"Total scanned by all queries: **{total_bytes / 1e9:.1f} GB** (free tier: 1,000 GB per month).\n")
    (ROOT / "docs").mkdir(exist_ok=True)
    (ROOT / "docs" / "answers.md").write_text("\n".join(out), encoding="utf-8")
    (ROOT / "docs" / "answers.json").write_text(json.dumps(results, indent=1), encoding="utf-8")
    print(f"total scanned: {total_bytes / 1e9:.2f} GB")


if __name__ == "__main__":
    main()
