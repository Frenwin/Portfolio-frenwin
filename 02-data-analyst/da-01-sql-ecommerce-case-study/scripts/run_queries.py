"""Run every query in queries/ against the DE-1 warehouse and write docs/answers.md.

Usage:
    python scripts/run_queries.py            # warehouse on localhost:5434 (DE-1 docker compose)
"""

from __future__ import annotations

import json
import os
import time
from decimal import Decimal
from pathlib import Path

import psycopg2

ROOT = Path(__file__).resolve().parents[1]


def connect():
    return psycopg2.connect(
        host=os.getenv("WAREHOUSE_HOST", "localhost"),
        port=int(os.getenv("WAREHOUSE_PORT", "5434")),
        dbname=os.getenv("WAREHOUSE_DB", "warehouse"),
        user=os.getenv("WAREHOUSE_USER", "warehouse"),
        password=os.getenv("WAREHOUSE_PASSWORD", "warehouse"),
    )


def fmt(value) -> str:
    if value is None:
        return ""
    if isinstance(value, (int,)) and not isinstance(value, bool):
        return f"{value:,}"
    if isinstance(value, Decimal):
        return f"{value:,}" if value == value.to_integral_value() and abs(value) >= 1000 else str(value)
    return str(value)


def markdown_table(columns: list[str], rows: list[tuple]) -> str:
    lines = ["| " + " | ".join(columns) + " |", "| " + " | ".join("---" for _ in columns) + " |"]
    lines += ["| " + " | ".join(fmt(v) for v in row) + " |" for row in rows]
    return "\n".join(lines)


def header(sql: str) -> tuple[str, str]:
    comments = []
    for line in sql.splitlines():  # only the comment block at the top of the file
        if not line.startswith("--"):
            break
        comments.append(line[2:].strip())
    question = comments[0] if comments else ""
    technique = " ".join(c for c in comments[1:]).removeprefix("Techniques:").strip()
    return question, technique


def main() -> None:
    conn = connect()
    out = ["# Answers", "", "Generated by `python scripts/run_queries.py` against the DE-1 warehouse. "
           "Definitions: [metric_definitions.md](metric_definitions.md).", ""]
    results = {}
    for path in sorted((ROOT / "queries").glob("q*.sql")):
        sql = path.read_text(encoding="utf-8")
        question, technique = header(sql)
        t = time.perf_counter()
        with conn.cursor() as cur:
            cur.execute(sql)
            columns = [d.name for d in cur.description]
            rows = cur.fetchall()
        conn.rollback()
        ms = (time.perf_counter() - t) * 1000
        results[path.stem] = {"columns": columns, "rows": [[float(v) if isinstance(v, Decimal) else v for v in r] for r in rows]}
        out += [
            f"## {question}",
            "",
            f"**SQL techniques:** {technique} · [`{path.name}`](../queries/{path.name}) · {ms:.0f} ms",
            "",
            markdown_table(columns, rows),
            "",
        ]
        print(f"{path.name}: {len(rows)} rows in {ms:.0f} ms")
    (ROOT / "docs" / "answers.md").write_text("\n".join(out), encoding="utf-8")
    (ROOT / "docs" / "answers.json").write_text(json.dumps(results, indent=1, default=str), encoding="utf-8")


if __name__ == "__main__":
    main()
